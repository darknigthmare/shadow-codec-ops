// Optional real-browser smoke test. Supply CQC_BROWSER_PATH when no Playwright browser is installed.
import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {readFile, mkdir, writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve, extname, sep} from 'node:path';
const {chromium}=await import(process.env.CQC_PLAYWRIGHT_MODULE||'playwright');
const root=fileURLToPath(new URL('../',import.meta.url));
const output=process.env.CQC_QA_OUTPUT||'/tmp/cqc-p74-ui-qa';
await mkdir(output,{recursive:true});
const server=createServer(async(req,res)=>{try{const path=resolve(root,'.'+new URL(req.url,'http://localhost').pathname);if(!path.startsWith(root+sep)&&!path.startsWith(root))throw Error('outside fixture');const body=await readFile(path);res.setHeader('Content-Type',extname(path)==='.html'?'text/html':'text/javascript');res.end(body);}catch{res.statusCode=404;res.end('Not found');}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
const errors=[];
const checks=[];
try{
 browser=await chromium.launch({headless:true,...(process.env.CQC_BROWSER_PATH?{executablePath:process.env.CQC_BROWSER_PATH}:{}),args:['--no-sandbox','--no-zygote','--single-process','--disable-gpu','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1280,height:800}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`http://127.0.0.1:${server.address().port}/scripts/fixtures/cqc-p74-team-ui.html`);
 assert.equal(await page.locator('#teamHudP74').isVisible(),false);
 await page.locator('summary').click();
 await page.locator('#teamEnabledP74').check();
 await page.locator('#teamReserveP74_0').selectOption('Charlie');
 await page.locator('#teamReserveP74_1').selectOption('Delta');
 await page.evaluate(()=>harness.start());
 assert.equal(await page.locator('#teamHudP74').isVisible(),true);
 assert.deepEqual(await page.evaluate(()=>harness.state.teams.map(t=>t.members.map(p=>p.f.uid))),[['Alpha','Charlie'],['Bravo','Delta']]);
 checks.push('native reserve selection starts the requested four authored fighters');
 const tag=page.getByRole('button',{name:'Joueur 1 : relais',exact:true});
 const assist=page.getByRole('button',{name:'Joueur 1 : assistance, coût 20 de jauge',exact:true});
 await tag.click();await page.evaluate(()=>harness.tick());
 assert.equal(await page.evaluate(()=>harness.state.teams[0].pending.kind),'tag');
 assert.equal(await tag.isDisabled(),true);
 await page.evaluate(()=>harness.tick(29));
 assert.equal(await page.evaluate(()=>harness.state.a.f.uid),'Charlie');
 checks.push('pointer tag command enters startup, disables conflicting controls and changes active fighter at frame 30');
 await page.evaluate(()=>harness.tick(18));
 await assist.click();await page.evaluate(()=>harness.tick());
 assert.deepEqual(await page.evaluate(()=>[harness.state.teams[0].assist.phase,harness.state.a.meter]),['entry',40]);
 assert.equal(await assist.isDisabled(),true);
 await page.evaluate(()=>harness.tick(20));
 assert.equal(await page.evaluate(()=>harness.state.teams[0].members[0].r),5);
 checks.push('pointer assist command spends tactical meter, uses the reserve ammunition and observes cooldown');
 await page.evaluate(()=>{harness.state.teams[0].assist=null;harness.state.teams[0].tagCooldown=0;harness.state.teams[0].assistCooldown=0;harness.state.a.attack=null;harness.state.a.cool=0;harness.pause(true);});
 assert.equal(await tag.isDisabled(),true);assert.equal(await assist.isDisabled(),true);
 assert.equal(await page.evaluate(()=>harness.ui.queueAction(0,'tag')),false);
 await page.evaluate(()=>harness.pause(false));
 assert.equal(await tag.isDisabled(),false);
 checks.push('pause blocks pointer controls and the public queue API');
 const desktop=await tag.boundingBox();assert.ok(desktop.height>=44);
 await page.screenshot({path:resolve(output,'team-ui-desktop.png'),fullPage:true});
 await page.setViewportSize({width:390,height:844});
 const mobile=await page.locator('#teamHudP74 button').evaluateAll(buttons=>buttons.map(b=>{const r=b.getBoundingClientRect();return{x:r.x,right:r.right,width:r.width,height:r.height};}));
 assert.ok(mobile.every(b=>b.x>=0&&b.right<=390&&b.height>=44));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:resolve(output,'team-ui-mobile.png'),fullPage:true});
 checks.push('desktop and 390px mobile commands remain inside the viewport with 44px touch height');
 assert.deepEqual(errors,[]);
 const report={status:'passed',harness:'isolated actual P74 controls + existing combat engine; not the full v055 runtime',browser:await browser.version(),checks,errors};
 await writeFile(resolve(output,'team-ui-report.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report,null,2));
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
